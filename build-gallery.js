// Usage: node build-gallery.js
// Scans ./images and rewrites images.js so every image appears in the gallery.
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, 'images');
const EXT = /\.(png|jpe?g|webp|gif|svg|avif)$/i;

// Optional: custom titles by file name, e.g. "T1KFC.png": "T1 KFC"
const TITLES = {};

const files = fs
  .readdirSync(DIR)
  .filter(f => EXT.test(f))
  .sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' })
  );

const nice = f => {
  const t = f.replace(EXT, '').replace(/[_-]+/g, ' ').trim();
  return t.charAt(0).toUpperCase() + t.slice(1);
};

const items = files.map(
  f =>
    `  { file: ${JSON.stringify(f)}, title: ${JSON.stringify(TITLES[f] || nice(f))} }`
);

fs.writeFileSync(
  path.join(__dirname, 'images.js'),
  `// Generated by build-gallery.js. Re-run "node build-gallery.js" after adding images,
// or edit this list by hand.
const IMAGE_DIR = "images/";
const IMAGES = [
${items.join(',\n')}
];
`
);
console.log(`Wrote ${files.length} images to images.js`);
